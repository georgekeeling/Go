      void DrawDot(int x, int y)
      {
        // x,y = coordinates in thePoints array
        // convert y,y to pixels, draw dot if overlaps clip rectangle
        int xPix = cellSide + x * cellSide;
        int yPix = cellSide + y * cellSide;
        Rectangle dotRect = new Rectangle(xPix - dotRadius, yPix - dotRadius,
          dotRadius * 2, dotRadius * 2);
        if (e.ClipRectangle.IntersectsWith(dotRect))
        {
          e.Graphics.FillEllipse(brushBlack, dotRect);
        }
      }
      void DrawRedCircle(int x, int y)
      {
        int xPix = cellSide + x * cellSide;
        int yPix = cellSide + y * cellSide;
        myPen.Color = Color.Red;
        myPen.Width = 3;
        Rectangle stoneRect = new Rectangle(xPix - stoneRadius, yPix - stoneRadius,
         stoneRadius * 2, stoneRadius * 2);
        e.Graphics.DrawEllipse(myPen, stoneRect);
        myPen.Width = 1;
      }
      void DrawScore(int x, int y)
      {
        // draw from results of scoring
        if (!ScGui.haveScore || toolsOptions.ShowNone.Checked) return;
        if (x < 0 || x >= bSide || y < 0 || y >= bSide) { return; }
        int xPix = cellSide + (x) * cellSide;
        int yPix = cellSide + (y) * cellSide;
        Rectangle stoneRect = new Rectangle(xPix - stoneRadius, yPix - stoneRadius,
          stoneRadius * 2, stoneRadius * 2);
        if (!e.ClipRectangle.IntersectsWith(stoneRect))
        {
          return;
        }
        if (toolsOptions.ShowRemovals.Checked && ScGui.Removals[x,y] != Color.Empty)
        {
          DrawScore2(x, y, brushRed);
        }
        if (toolsOptions.ShowTerritory.Checked && ScGui.Territories[x, y] != Color.Empty)
        {
          if (ScGui.Territories[x, y] == Color.Black)
            DrawScore2(x, y, brushBlack);
          else
            DrawScore2(x, y, brushWhite);
        }
        if (toolsOptions.ShowConnections.Checked && ScGui.Connections[x, y] != Color.Empty)
        {
          if (ScGui.Connections[x, y] == Color.Black)
            DrawScore2(x, y, brushLightBlack);
          else
            DrawScore2(x, y, brushDarkWhite);
        }
      }
      void DrawScore2(int x, int y, Brush brush)
      {
        // x,y = coordinates in thePoints array
        // convert y,y to pixels, draw dot if overlaps clip rectangle
        int radius = dotRadius * 2;
        int xPix = cellSide + x * cellSide;
        int yPix = cellSide + y * cellSide;
        Rectangle rect = new Rectangle(xPix - radius, yPix - radius,
          radius * 2, radius * 2);
        if (e.ClipRectangle.IntersectsWith(rect))
        {
          DrawStar(xPix, yPix, brush);
        }
      }
      void DrawStar (int xP, int yP, Brush brush)
      {
        // xP,yP = centre of star in pixels
        int starPoints = 10;        // double number of points on star
        int starRadius1 = dotRadius;
        int starRadius2 = dotRadius * 2;
        Point[] star = new Point[starPoints];
        double angle = (new Random(RandomSeed++)).NextDouble();
        for (int i = 0; i < starPoints; i++)
        {
          double r = (i % 2 == 0) ? starRadius1 : starRadius2;
          star[i].X = (int)(xP + r * Math.Cos(angle));
          star[i].Y = (int)(yP + r * Math.Sin(angle));
          angle += 2 * Math.PI / starPoints;
        }
        e.Graphics.FillPolygon(brush, star);
      }

      void DrawStone(AStone[,] sourceStones, int x, int y, int xBase, int yBase)
      {
        // x,y = coordinates in sourceStones array
        // xBase, yBase = offset of sourceStones in board
        if (x < 0 || x >= bSide || y < 0 || y >= bSide) { return; }
        int xPix = cellSide + (x + xBase) * cellSide;
        int yPix = cellSide + (y + yBase) * cellSide;
        Rectangle stoneRect = new Rectangle(xPix - stoneRadius, yPix - stoneRadius,
          stoneRadius * 2, stoneRadius * 2);
        if (!e.ClipRectangle.IntersectsWith(stoneRect))
        {
          return;
        }
        switch (sourceStones[x, y].color)
        {
          case 1:
            e.Graphics.FillEllipse(brushWhite, stoneRect);
            break;
          case 2:
            e.Graphics.FillEllipse(brushBlack, stoneRect);
            break;
          case 129:
            e.Graphics.FillEllipse(brushDarkWhite, stoneRect);
            break;
          case 130:
            e.Graphics.FillEllipse(brushLightBlack, stoneRect);
            break;
        }
        if (sourceStones[x, y].moveAdded == 0 || !toolsOptions.showSequence) { return; }
        string s = sourceStones[x, y].moveAdded.ToString();
        SizeF size = e.Graphics.MeasureString(s, myFont);
        if (sourceStones[x, y].color == 1)
        {
          e.Graphics.DrawString(s, myFont, brushBlack, xPix - size.Width / 2, yPix - size.Height / 2);
        }
        if (sourceStones[x, y].color == 2)
        {
          e.Graphics.DrawString(s, myFont, brushWhite, xPix - size.Width / 2, yPix - size.Height / 2);
        }

      }

