    // MouseClick always precedes MouseUp with same coordinates
    // MouseDown precedes both, possibly different coordinates.
    // So we do not use MouseClick. It would be confusing
    // see FormCutCopyPaste.cs for more details (possibly)
    private void PanelMain_MouseUp(object sender, MouseEventArgs e)
    {
      if (ignoreNextMouseUp)
      {
        mouseDown = false;
        mouseDragging = false;
        ignoreNextMouseUp = false;
        return;
      }
      int boardX = BoardXYfromPixelXY(e.X);
      int boardY = BoardXYfromPixelXY(e.Y);
      panelMain.Focus();
      mouseDown = false;
      if (panelMain.Cursor == Cursors.Cross)
      {
        EndPaste(e);
        statusM.Clear();
        return;
      }
      if (panelMain.Cursor == Cursors.Hand)
      {
        // we were moving. If one stone and not moved and was quick, not much of a drag. 
        // in that case we want to treat like click
        bool properMove = true;
        long mouseWasDownMs = (DateTime.Now.Ticks / TimeSpan.TicksPerMillisecond) - mouseFirstDownMs;
        if ((selection.movePoints.GetLength(0) * selection.movePoints.GetLength(1) == 1) &&
          boardX == selection.TLx() && boardY == selection.TLy() &&
          mouseWasDownMs < 200)
        {
          properMove = false;
        }
        EndMove(e);
        if (properMove)
        {
          statusM.Clear();
          return;
        }
        UnSaveState("Mouse up");      // Commence move had a SaveState, which we dont need
      }
      mouseDown = false;
      if (!mouseDragging)
      {
        if (!selection.Cancel())
        {
          if (NearPoint(e.X, e.Y))
          {
            if (gameInProgress)
            {
              MouseUpInGame(boardX, boardY);
              return;
            }
            string statusMess = "";
            SaveState("Mouse Up");
            if (thePoints[boardX, boardY].color == 0)
            {
              byte colorAdded = 0;
              if (TSBwhite.Checked)
              {
                thePoints[boardX, boardY].color = 1;
                colorAdded = 1;
                statusMess = "White ";
              }
              else
              {
                thePoints[boardX, boardY].color = 2;
                colorAdded = 2;
                statusMess = "Black ";
              }
              if (!ProcessMove(boardX, boardY, colorAdded)) return;
              statusMess += "played at " + toolsOptions.topLabels[boardX] + " " + toolsOptions.leftLabels[boardY];
              if (TSBblackWhite.Checked)
              {
                TSBblack.Checked = !TSBblack.Checked;
                TSBwhite.Checked = !TSBwhite.Checked;
                if (TSBblack.Checked) { panelMain.Cursor = blackCursor; }
                else { panelMain.Cursor = whiteCursor; }
              }
            }
            else
            {
              // removing a stone by clicking on it
              if (thePoints[boardX, boardY].color == 1) { statusMess = "White"; } else { statusMess = "Black"; }
              statusMess += " stone removed from " + toolsOptions.topLabels[boardX] + " " + toolsOptions.leftLabels[boardY];
              thePoints[boardX, boardY].color = 0;
              thePoints[boardX, boardY].moveAdded = 0;
            }
            if (TSBblack.Checked) { statusMess += ". Black to play"; } else { statusMess += ". White to play"; }
            EndMove(boardX, boardY, statusMess);
          }
        }
        return;
      }
      mouseDragging = false;
    }
    private bool ProcessMove(int boardX, int boardY, byte colorAdded)
    {
      int captures = CountCaptures(boardX, boardY);
      if (captures == 0)
      {
        // check for suicide
        if (CountLiberties(boardX, boardY) == 0)
        {
          // it is suicide. Not allowed. Rewind a bit
          thePoints[boardX, boardY].color = 0;
          UnSaveState("Mouse up suicide");
          new MyMessageBox("Suicide not allowed", this);
          return false;
        }
      }
      if (captures == 1)
      {
        // Check Ko. Temporarily remove prisoner
        thePoints[firstPrisoner.X, firstPrisoner.Y].color = 0;
        if (CheckForKo())
        {
          thePoints[boardX, boardY].color = 0;
          thePoints[firstPrisoner.X, firstPrisoner.Y].color = (byte)(3 - colorAdded);
          UnSaveState("Mouse up Ko");
          new MyMessageBox("Ko not allowed", this);
          return false;
        }
        thePoints[firstPrisoner.X, firstPrisoner.Y].color = (byte)(3 - colorAdded);
      }
      thePoints[boardX, boardY].moveAdded = GetNextMoveNr();
      ImprisonCaptures(boardX, boardY);
      return true;
    }
    private void EndMove(int boardX, int boardY, string message)
    {
      statusM.Set(message);
      panelMain.Invalidate(PixRectFromBoardXY(boardX, boardY));
      RedCirclesRemoveOld();
      prSLider.Invalidate();
    }
    private short GetNextMoveNr()
    {
      short nextMoveNr = 0;
      for (int x = 0; x < bSide; x++)
      {
        for (int y = 0; y < bSide; y++)
        {
          if (thePoints[x, y].moveAdded > nextMoveNr)
          {
            nextMoveNr = thePoints[x, y].moveAdded;
          }
        }
      }
      return ++nextMoveNr;
    }
    private void PanelMain_MouseDown(object sender, MouseEventArgs e)
    {
      panelMain.Focus();
      if (panelMain.Cursor == Cursors.Cross) return;
      int boardX = BoardXYfromPixelXY(e.X);
      int boardY = BoardXYfromPixelXY(e.Y);
      mouseFirstDownMs = DateTime.Now.Ticks / TimeSpan.TicksPerMillisecond;
      // if in selection rectangle, commence move
      if (boardX >= selection.TLx() && boardX <= selection.BRx() &&
        boardY >= selection.TLy() && boardY <= selection.BRy())
      {
        // SaveState("Mouse down, commence move 1");
        if (gameInProgress) { return; }
        selection.StartDrag();
        TLpasteCx = selection.TLx(); TLpasteCy = selection.TLy();
        BRpasteCx = selection.BRx(); BRpasteCy = selection.BRy();
        mouseDown = true;
        panelMain.Cursor = Cursors.Hand;
        return;
      }
      if (!NearPoint(e.X, e.Y))
      {
        mouseDragging = false;
        mouseDown = true;
        mouseDownX = e.X;
        mouseDownY = e.Y;
        return;
      }
      // we are near a point. If it is a stone, select it
      if (thePoints[boardX, boardY].color == 0)
      {
        mouseDragging = false;
        mouseDown = true;
        mouseDownX = e.X;
        mouseDownY = e.Y;
        return;
      }
      // is a stone, select it and start moving it
      // SaveState("Mouse down, commence move 2");
      if (gameInProgress) { return; }
      selection.UpdateRect(e.X, e.Y, e.X, e.Y);
      selection.StartDrag();
      TLpasteCx = boardX; TLpasteCy = boardY; BRpasteCx = boardX; BRpasteCy = boardY;
      mouseDragging = false;
      mouseDown = true;
      panelMain.Cursor = Cursors.Hand;
    }
