    private void PanelMain_MouseMove(object sender, MouseEventArgs e)
    {
      Point thePoint = NearBoardXY(e.X, e.Y);
      if (thePoint.X != -1)
      {
        if (mouseBoardX != thePoint.X || mouseBoardY != thePoint.Y)
        {
          mouseMoveTimer.Stop();
          UpdateTSTextBox1(toolsOptions.topLabels[thePoint.X] + " " +
            toolsOptions.leftLabels[thePoint.Y]);
        }
        mouseMoveTimer.Start();
      }
      else
      {
        mouseMoveTimer.Stop();
        UpdateTSTextBox1("");
      }
      mouseBoardX = thePoint.X;
      mouseBoardY = thePoint.Y;

      if ((panelMain.Cursor == Cursors.Cross) || (panelMain.Cursor == Cursors.Hand))
      {
        int newEX = BoardXYfromPixelXY(e.X);
        int newEY = BoardXYfromPixelXY(e.Y);

        if ((newEX == TLpasteCx) && (newEY == TLpasteCy)) return;
        if (!LegalMove(newEX, newEY)) return;

        panelMain.Invalidate(PixRectFromBoardRect(TLpasteCx, TLpasteCy,
          BRpasteCx, BRpasteCy));
        BRpasteCx += newEX - TLpasteCx;
        BRpasteCy += newEY - TLpasteCy;
        TLpasteCx = newEX;
        TLpasteCy = newEY;
        panelMain.Invalidate(PixRectFromBoardRect(TLpasteCx, TLpasteCy,
          BRpasteCx, BRpasteCy));
        return;
      }
      if (!mouseDown) return;
      const int margin = 2;
      if (e.X >= mouseDownX - margin && e.X <= mouseDownX + margin &&
        e.Y >= mouseDownY - margin && e.Y <= mouseDownY + margin)
      {
        return;   // have not moved enough to start creation of selection rectangle
      }
      // we have mouseDownX, mouseDownY as one corner of selection rectangle
      // and e.X, e.Y as other corner
      // arrange them so that first pair is top left corner, second is bottom right
      int BRx = e.X; int BRy = e.Y;
      int TLx = mouseDownX; int TLy = mouseDownY;
      if (BRx < TLx) { (TLx, BRx) = (BRx, TLx); }
      if (BRy < TLy) { (TLy, BRy) = (BRy, TLy); }
      selection.UpdateRect(TLx, TLy, BRx, BRy);
      mouseDragging = true;
    }
    private bool LegalMove(int x, int y)
    {
      // single stone may only move onto self or empty point. Cannot move onto any prisoner either
      if (selection.movePoints.GetLength(0) * selection.movePoints.GetLength(1) == 1 &&
        thePoints[x, y].color != 0)
      {
        // not allowed to paste singleton on top of existing stone
        // unless it is the original stone, which must be the only stone with top bit set
        if ((thePoints[x, y].color & 0x80) != 0x80)
          return false;
      }
      return true;
    }
    private bool NearPoint(int x, int y)
    {
      int cellSide = PixelXYfromBoardXY(0);
      int nearestPx = PixelXYfromBoardXY(BoardXYfromPixelXY(x));
      int nearestPy = PixelXYfromBoardXY(BoardXYfromPixelXY(y));

      return (Math.Abs(nearestPx - x) <= cellSide / 3) && (Math.Abs(nearestPy - y) <= cellSide / 3);
    }
    private Point NearBoardXY(int x, int y)
    {
      Point result = new Point(BoardXYfromPixelXY(x), BoardXYfromPixelXY(y));
      if (!NearPoint(x, y))
      {
        result.X = -1;
      }
      return result;
    }
    public int BoardXYfromPixelXY(int pixelXY)
    {
      int squareSide = panelMain.Width;
      if (panelMain.Height < squareSide) { squareSide = panelMain.Height; }
      int cellSide = squareSide / (bSide + 1);
      int index = (pixelXY - cellSide / 2) / cellSide;   //... / 2 for rounding
      if (index < 0) { return 0; }
      if (index >= bSide) { return bSide - 1; }
      return index;
    }
    public int PixelXYfromBoardXY(int boardXY)
    {
      int squareSide = panelMain.Width;
      if (panelMain.Height < squareSide) { squareSide = panelMain.Height; }
      int cellSide = squareSide / (bSide + 1);
      return cellSide + cellSide * boardXY;
    }
    public Rectangle PixRectFromBoardXY(int boardX, int boardY)
    {
      int side = PixelXYfromBoardXY(0);
      Rectangle rc = new Rectangle(0, 0, side, side)
      {
        X = PixelXYfromBoardXY(boardX) - side / 2,
        Y = PixelXYfromBoardXY(boardY) - side / 2
      };
      return rc;
    }
    public Rectangle BoardRectFromPixRect(Rectangle rectangle)
    {
      int width = BoardXYfromPixelXY(rectangle.Width);
      int height = BoardXYfromPixelXY(rectangle.Height);
      Rectangle rc = new Rectangle(0, 0, width, height)
      {
        X = BoardXYfromPixelXY(rectangle.X),
        Y = BoardXYfromPixelXY(rectangle.Y)
      };
      return rc;
    }
    public Rectangle PixRectFromBoardRect(int TRx, int TRy, int BRx, int BRy)
    {
      // pixel rectangle is half a cell outside (TRx, TRy), (BRx, BRy)
      int side = PixelXYfromBoardXY(0);
      int width = PixelXYfromBoardXY(BRx) - PixelXYfromBoardXY(TRx) + side;
      int height = PixelXYfromBoardXY(BRy) - PixelXYfromBoardXY(TRy) + side;
      Rectangle rc = new Rectangle(0, 0, width, height)
      {
        X = PixelXYfromBoardXY(TRx) - side / 2,
        Y = PixelXYfromBoardXY(TRy) - side / 2
      };
      return rc;
    }
    private float GetFontSizeForHeight(Graphics graphics, string fontName, float desiredHeight)
    {
      float fontSize = 1.0f;
      Font font = new Font(fontName, fontSize);
      SizeF size = graphics.MeasureString("A", font);

      // Increase font size until the height of 'A' is close to the desired height
      while (size.Height < desiredHeight)
      {
        fontSize += 0.5f;
        font = new Font(fontName, fontSize);
        size = graphics.MeasureString("A", font);
      }

      return fontSize;
    }

