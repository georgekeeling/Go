    {
      Stopwatch stopWatch = new Stopwatch();
      stopWatch.Start();
      // panelMain must be big enough for 18 + 2 squares (assuming bSide = 19)
      myPen.Color = Color.Black;
      int cellSide = PixelXYfromBoardXY(0);
      int squareSide = cellSide * (bSide + 1);
      int dotRadius = cellSide / 8;
      int stoneRadius = (int)(cellSide / 2.2);
      int RandomSeed = (DateTime.Now).Millisecond;
      Rectangle drawStones = BoardRectFromPixRect(e.ClipRectangle);

