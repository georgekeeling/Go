    public AStone[,] CreateStones(int xDim, int yDim)
    {
      AStone[,] returnVal = new AStone[xDim, yDim];
      for (int x = 0; x < xDim; x++)
      {
        for (int y = 0; y < yDim; y++)
        {
          returnVal[x, y] = new AStone();
        }
      }
      return returnVal;
    }
    public bool LooksEqualTo (AStone st1, AStone st2)
    {
      if (st1.color != st2.color) { return false; }
      if (!toolsOptions.showSequence) { return true; }
      // colors are same
      return (st1.moveAdded == st2.moveAdded);
    }
    public void StonesOnBoard (ref int whites, ref int blacks)
    {
      whites = 0; blacks = 0;
      for (int x = 0; x < bSide; x++)
      {
        for (int y = 0; y < bSide; y++)
        {
          if (thePoints[x, y].color == 1) { whites++; }
          if (thePoints[x, y].color == 2) { blacks++; }
        }
      }
    }

