      for (int lineX = cellSide; lineX <= (squareSide - cellSide); lineX += cellSide)
      {
        if (lineX >= e.ClipRectangle.Left && lineX <= e.ClipRectangle.Right)
        {
          e.Graphics.DrawLine(myPen, lineX, cellSide, lineX, cellSide * bSide);
        }
      }
      for (int lineY = cellSide; lineY <= (squareSide - cellSide); lineY += cellSide)
      {
        if (lineY >= e.ClipRectangle.Top && lineY <= e.ClipRectangle.Bottom)
        {
          e.Graphics.DrawLine(myPen, cellSide, lineY, cellSide * bSide, lineY);
        }
      }
