    private void GetSetNames()
    {
      // AssemblyTitleAttribute and AssemblyFileVersionAttribute come from AssemblyInfo.cs
      // AssemblyInfo.cs provides info for file properties
      Assembly assembly = Assembly.GetExecutingAssembly();
      AssemblyTitleAttribute assemblyTitle = assembly.GetCustomAttribute<AssemblyTitleAttribute>();
      AssemblyFileVersionAttribute fileVersion = assembly.GetCustomAttribute<AssemblyFileVersionAttribute>();
      string keyName = "HKEY_CLASSES_ROOT\\Local Settings\\Software\\Microsoft\\Windows\\Shell\\MuiCache\\";
      string valueName = assembly.Location + ".FriendlyAppName";
      // assembly.Location = path of .exe file
      // in debug that's C:\Users\georg\My Drive\repos\Go\Go\bin\Debug\Go.exe.FriendlyAppName

      // build date is in format dd/mm/yyyy, generated by pre-build event into resources BuildDate.txt
      // see Go (project) right-click / Properties / Build Events and Resources tabs
      string day = Properties.Resources.BuildDate.Substring(0, 2);
      string month = Properties.Resources.BuildDate.Substring(3, 2);
      string year = Properties.Resources.BuildDate.Substring(6, 4);
      DateTime buildDate = new DateTime(int.Parse(year), int.Parse(month), int.Parse(day), 0,0,0,0);

      programTitle = assemblyTitle.Title;
      Text = programTitle;      // title bar of main form    
      programVersion = fileVersion.Version;
      programBuildDate = buildDate.ToLongDateString();

      // now get programTitle into registry entry for this instance (if not already there)
      // see https://learn.microsoft.com/en-us/dotnet/api/microsoft.win32.registry?view=net-9.0 
      try
      {
        bool updateNeeded = false;
        object testValue = Registry.GetValue(keyName, valueName, "");
        if (testValue == null) 
        {  
          updateNeeded = true;
        }
        else
        {
          if (testValue.GetType().Name != "String")
          {
            updateNeeded = true;
          }
          else 
          {
            if ((string)testValue != programTitle)
            {
              updateNeeded = true;
            }
          }
        }
        if (updateNeeded)
        {
          Registry.SetValue(keyName, valueName, programTitle);
        }
      }
      catch (Exception ex) 
      {
        new MyMessageBox(ex.Message, "Registry Error", this);
      }
    }

    private Cursor SetCustomCursor(string fileName)
    {
      // Load the custom cursor image from the embedded resources
      // it must have properties / Build Action: Embedded Resource
      Assembly assembly = Assembly.GetExecutingAssembly();
      using (Stream stream = assembly.GetManifestResourceStream("GoPlanner.img." + fileName +".png"))
      {
        if (stream != null)
        {
          Bitmap cursorBitmap = new Bitmap(stream);
          IntPtr cursorPtr = cursorBitmap.GetHicon();
          return new Cursor(cursorPtr);
        }
      }
      return null;
    }
