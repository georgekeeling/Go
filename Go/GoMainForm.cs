  public class AStone
  {
    public byte color;      // 0 blank, 1 white, 2 black, top bit set = pasting
    public short moveAdded;
    public AStone()
    {
      color = 0;
      moveAdded = 0;
    }
    public bool EqualTo(AStone other)
    {
      return (color == other.color) && (moveAdded == other.moveAdded);
    }
